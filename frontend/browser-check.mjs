import { chromium as playwright } from '@playwright/test';
import chromium from '@sparticuz/chromium';
import AxeBuilder from '@axe-core/playwright';
import fs from 'node:fs';
const browser=await playwright.launch({...(process.env.BROWSER_EXECUTABLE_PATH ? {executablePath:process.env.BROWSER_EXECUTABLE_PATH,args:chromium.args} : {}),headless:true});
const baseUrl=process.env.E2E_BASE_URL || 'http://127.0.0.1:8080';
const errors=[];
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
page.on('pageerror',e=>errors.push(e.message));
await page.goto(baseUrl);
await page.getByLabel('Email',{exact:true}).fill('requester@sandbox.test');
await page.getByLabel('Password',{exact:true}).fill('SandboxOnly!2026');
await page.getByRole('button',{name:'Masuk ke workspace'}).click();
await page.getByRole('heading',{name:'Setiap pengadaan, terkendali.'}).waitFor();
fs.mkdirSync('../docs/qa',{recursive:true});
await page.screenshot({path:'../docs/qa/dashboard-desktop.png',fullPage:true});
let axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
const results={desktop:{violations:axe.violations.map(x=>({id:x.id,impact:x.impact,description:x.description,nodes:x.nodes.map(n=>n.target)}))},pageErrors:errors};
await page.getByRole('link',{name:'Permintaan pembelian',exact:true}).click();
await page.getByRole('link',{name:'Buat dokumen'}).click();
await page.getByLabel('Judul',{exact:true}).fill('Browser QA purchase requisition');
await page.getByLabel('Deskripsi',{exact:true}).fill('Laptop for operations team');
await page.getByLabel('Unit price',{exact:true}).fill('5000000');
await page.getByRole('button',{name:'Simpan draft'}).click();
await page.getByRole('heading',{name:'Browser QA purchase requisition',exact:true}).waitFor();
await page.getByRole('button',{name:'Ajukan persetujuan'}).click();
await page.getByLabel('Reason / notes').fill('Equipment needed for operations');
await page.getByRole('button',{name:'Confirm action'}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
await page.screenshot({path:'../docs/qa/pr-detail-desktop.png',fullPage:true});
results.prCreationAndSubmission='passed';
await page.setViewportSize({width:390,height:844});
await page.goto(baseUrl);
await page.getByRole('heading',{name:'Setiap pengadaan, terkendali.'}).waitFor();
await page.screenshot({path:'../docs/qa/dashboard-mobile.png',fullPage:true});
results.mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
results.mobile={violations:axe.violations.map(x=>({id:x.id,impact:x.impact,description:x.description,nodes:x.nodes.map(n=>n.target)}))};
fs.writeFileSync('../docs/qa/browser-check.json',JSON.stringify(results,null,2));
await browser.close();
console.log(JSON.stringify(results,null,2));
